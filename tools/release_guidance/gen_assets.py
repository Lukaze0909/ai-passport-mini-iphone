#!/usr/bin/env python3
"""Generate Release Guidance sky sprites and key sounds as C sources.

Usage: python3 tools/release_guidance/gen_assets.py
Requires Pillow and NumPy (developer machine only; not needed for building).
Outputs:
  main/rg/rg_images.c      LVGL 9 image descriptors (A8 / RGB565A8, Flash const)
  main/rg/rg_sound_data.c  24 kHz mono PCM16 key sounds sliced from assets/music
preview.py imports the sprite functions so host previews use the same pixels.
"""
import sys
import wave
from pathlib import Path

import numpy as np
from PIL import Image, ImageDraw, ImageFilter

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import rg_spec as S  # noqa: E402

SS = 3  # supersampling factor
HEADER = "// Generated by tools/release_guidance/gen_assets.py. Do not edit.\n"


def rgb(hexv):
    return ((hexv >> 16) & 255, (hexv >> 8) & 255, hexv & 255)


def downsample(arr, w, h):
    im = Image.fromarray(np.clip(arr * 255.0, 0, 255).astype(np.uint8), "L")
    return np.asarray(im.resize((w, h), Image.LANCZOS)).astype(np.float64) / 255.0


# ---------------------------------------------------------------- sprites
def cloud_sprite(scale, color):
    """RGBA uint8 array: soft puffs with a clean, uniform colour; only alpha
    fades toward the rim (no dark halo)."""
    ext_l = min(dx - r for dx, _, r in S.CLOUD_PUFFS) * scale
    ext_r = max(dx + r for dx, _, r in S.CLOUD_PUFFS) * scale
    ext_t = min(dy - r for _, dy, r in S.CLOUD_PUFFS) * scale
    ext_b = max(dy + r for _, dy, r in S.CLOUD_PUFFS) * scale
    m = 6
    w = int(np.ceil(ext_r - ext_l)) + 2 * m
    h = int(np.ceil(ext_b - ext_t)) + 2 * m
    cx, cy = m - ext_l, m - ext_t
    mask = Image.new("L", (w * SS, h * SS), 0)
    d = ImageDraw.Draw(mask)
    for dx, dy, r in S.CLOUD_PUFFS:
        x, y, rr = (cx + dx * scale) * SS, (cy + dy * scale) * SS, r * scale * SS
        d.ellipse([x - rr, y - rr, x + rr, y + rr], fill=255)
    mask = mask.filter(ImageFilter.GaussianBlur(S.CLOUD_BLUR * SS))
    k = downsample(np.asarray(mask).astype(np.float64) / 255.0, w, h)
    out = np.zeros((h, w, 4), np.float64)
    c = np.array(rgb(color), np.float64)
    out[..., :3] = c                     # uniform colour, clean edge
    out[..., 3] = k * 255.0
    return out.astype(np.uint8), (int(round(cx)), int(round(cy)))


def disc_alpha(size, cx, cy, r):
    yy, xx = np.mgrid[0:size * SS, 0:size * SS]
    dist = np.hypot((xx + 0.5) / SS - cx, (yy + 0.5) / SS - cy)
    return np.clip(r - dist + 0.5, 0, 1)


def moon_sprite():
    g = S.MOON["glow"]
    size = 2 * g
    c = g
    body = disc_alpha(size, c, c, S.MOON["r"]) * (1 - disc_alpha(size, c + 5, c - 3, S.MOON["r"] - 1))
    yy, xx = np.mgrid[0:size * SS, 0:size * SS]
    dist = np.hypot((xx + 0.5) / SS - c, (yy + 0.5) / SS - c)
    glow = np.clip(1 - dist / g, 0, 1) ** 2 * 0.28
    a = body + (1 - body) * glow
    return downsample(a, size, size)


def sun_body_sprite():
    g = S.SUN["glow"]
    size = 2 * g
    c = g
    body = disc_alpha(size, c, c, S.SUN["r"])
    yy, xx = np.mgrid[0:size * SS, 0:size * SS]
    dist = np.hypot((xx + 0.5) / SS - c, (yy + 0.5) / SS - c)
    glow = np.clip(1 - dist / g, 0, 1) ** 1.6 * 0.35
    return downsample(body + (1 - body) * glow, size, size)


def sun_rays_sprite():
    size = 2 * (S.SUN["ray_out"] + 2)
    c = size / 2
    im = Image.new("L", (size * SS, size * SS), 0)
    d = ImageDraw.Draw(im)
    for i in range(S.SUN["rays"]):
        ang = np.radians(i * 360.0 / S.SUN["rays"])
        x0, y0 = c + S.SUN["ray_in"] * np.cos(ang), c + S.SUN["ray_in"] * np.sin(ang)
        x1, y1 = c + S.SUN["ray_out"] * np.cos(ang), c + S.SUN["ray_out"] * np.sin(ang)
        d.line([(x0 * SS, y0 * SS), (x1 * SS, y1 * SS)], fill=230, width=int(1.4 * SS))
    return downsample(np.asarray(im).astype(np.float64) / 255.0, size, size)


def rainbow_sprite():
    r, band, n = S.RAINBOW["r"], S.RAINBOW["band"], len(S.RAINBOW["colors"])
    half = band * n / 2.0
    w = int(2 * (r + half + 3))
    h = int(r + half + 3)
    cx, cy = w / 2.0, h + 0.0  # centre sits just below the sprite's bottom edge
    yy, xx = np.mgrid[0:h * SS, 0:w * SS]
    px, py = (xx + 0.5) / SS - cx, (yy + 0.5) / SS - cy
    dist = np.hypot(px, py)
    ang = np.degrees(np.abs(np.arctan2(px, -py)))       # 0 at the top, 90 at the ends
    fade = np.clip((88 - ang) / 40.0, 0, 1)
    rgbacc = np.zeros(dist.shape + (3,))
    alpha = np.zeros(dist.shape)
    for i, col in enumerate(S.RAINBOW["colors"]):       # outer band first (red)
        r_out = r + half - i * band
        cov = np.clip(r_out - dist, 0, 1) * np.clip(dist - (r_out - band), 0, 1)
        rgbacc += cov[..., None] * np.array(rgb(col))
        alpha += cov
    alpha = np.clip(alpha, 0, 1)
    colour = rgbacc / np.maximum(alpha, 1e-6)[..., None]
    a = alpha * fade
    img = Image.fromarray(np.dstack([colour, a * 255]).clip(0, 255).astype(np.uint8), "RGBA")
    img = img.filter(ImageFilter.GaussianBlur(0.8 * SS))
    img = img.resize((w, h), Image.LANCZOS)
    arr = np.asarray(img).astype(np.float64)
    arr[..., 3] *= S.RAINBOW["opa"] / 255.0
    return arr.astype(np.uint8)


def leaf_sprite():
    w, h = 10, 6
    im = Image.new("L", (w * SS, h * SS), 0)
    d = ImageDraw.Draw(im)
    d.ellipse([0.5 * SS, 0.8 * SS, 9.5 * SS, 5.2 * SS], fill=255)
    d.polygon([(0, 3 * SS), (1.6 * SS, 2.4 * SS), (1.6 * SS, 3.6 * SS)], fill=255)
    return downsample(np.asarray(im).astype(np.float64) / 255.0, w, h)


BAYER4 = np.array([[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]], np.float64)
GRADIENT_TILE_W = 8
GRADIENT_GAMMA = 0.9


def gradient_rgb(pal):
    """Float RGB rows (H x 3) of the vertical sky gradient, gamma-shaped."""
    top, bot = np.array(rgb(pal["top"]), np.float64), np.array(rgb(pal["bottom"]), np.float64)
    t = (np.arange(S.SCREEN_H) / (S.SCREEN_H - 1.0)) ** GRADIENT_GAMMA
    return top + (bot - top) * t[:, None]


def gradient_tile(pal):
    """8 x 320 RGB565 tile with 4x4 ordered dithering (no banding on RGB565);
    the firmware tiles it horizontally across the screen."""
    rows = gradient_rgb(pal)
    h, w = S.SCREEN_H, GRADIENT_TILE_W
    thr = (BAYER4[np.arange(h)[:, None] % 4, np.arange(w)[None, :] % 4] + 0.5) / 16.0
    out = np.zeros((h, w, 3), np.uint16)
    for ch, bits in enumerate((5, 6, 5)):
        levels = (1 << bits) - 1
        v = rows[:, ch][:, None] / 255.0 * levels
        out[..., ch] = np.clip(np.floor(v + thr), 0, levels).astype(np.uint16)
    return out


def all_sprites():
    """name -> (kind, data, pivot) ; kind 'a8' (float 0..1) or 'rgba' (uint8)."""
    sprites = {}
    for i, (_, _, sc) in enumerate(S.CLOUDS):
        for theme in ("dusk", "morning"):
            arr, pivot = cloud_sprite(sc, S.THEMES[theme]["cloud"])
            sprites[f"cloud{i}_{theme}"] = ("rgba", arr, pivot)
    m = moon_sprite()
    sprites["moon"] = ("a8", m, (m.shape[1] // 2, m.shape[0] // 2))
    sb = sun_body_sprite()
    sprites["sun_body"] = ("a8", sb, (sb.shape[1] // 2, sb.shape[0] // 2))
    sr = sun_rays_sprite()
    sprites["sun_rays"] = ("a8", sr, (sr.shape[1] // 2, sr.shape[0] // 2))
    rb = rainbow_sprite()
    sprites["rainbow"] = ("rgba", rb, (rb.shape[1] // 2, rb.shape[0]))
    for name, pal in S.THEMES.items():
        sprites[f"sky_{name}"] = ("rgb565", gradient_tile(pal), (0, 0))
    lf = leaf_sprite()
    sprites["leaf"] = ("a8", lf, (lf.shape[1] // 2, lf.shape[0] // 2))
    return sprites


def c_bytes(data, indent="    ", per_line=16):
    out = []
    for i in range(0, len(data), per_line):
        out.append(indent + ", ".join(f"0x{b:02X}" for b in data[i:i + per_line]) + ",")
    return "\n".join(out)


def emit_images(sprites):
    parts = [HEADER, '#include "rg_images.h"\n\n']
    hdr = [HEADER, "#pragma once\n\n#include \"lvgl.h\"\n\n"]
    total = 0
    for name, (kind, data, pivot) in sprites.items():
        if kind == "rgb565":
            h, w = data.shape[:2]
            px = ((data[..., 0] << 11) | (data[..., 1] << 5) | data[..., 2]).astype("<u2")
            payload = px.tobytes()
            cf, stride = "LV_COLOR_FORMAT_RGB565", w * 2
        elif kind == "a8":
            a = np.clip(np.round(data * 255), 0, 255).astype(np.uint8)
            h, w = a.shape
            payload = a.tobytes()
            cf, stride = "LV_COLOR_FORMAT_A8", w
        else:
            h, w = data.shape[:2]
            r = data[..., 0].astype(np.uint16) >> 3
            g = data[..., 1].astype(np.uint16) >> 2
            b = data[..., 2].astype(np.uint16) >> 3
            px = ((r << 11) | (g << 5) | b).astype("<u2")
            payload = px.tobytes() + data[..., 3].astype(np.uint8).tobytes()
            cf, stride = "LV_COLOR_FORMAT_RGB565A8", w * 2
        total += len(payload)
        parts.append(f"static const uint8_t {name}_map[] __attribute__((aligned(4))) = {{\n{c_bytes(payload)}\n}};\n\n")
        parts.append(
            f"const lv_image_dsc_t rg_img_{name} = {{\n"
            f"    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
            f"    .header.cf = {cf},\n"
            f"    .header.w = {w},\n    .header.h = {h},\n    .header.stride = {stride},\n"
            f"    .data_size = sizeof({name}_map),\n    .data = {name}_map,\n}};\n\n")
        hdr.append(f"extern const lv_image_dsc_t rg_img_{name};  // {w}x{h} {cf[16:]}\n")
        hdr.append(f"#define RG_IMG_{name.upper()}_PIVOT_X {pivot[0]}\n")
        hdr.append(f"#define RG_IMG_{name.upper()}_PIVOT_Y {pivot[1]}\n")
    (ROOT / "main/rg/rg_images.c").write_text("".join(parts), encoding="utf-8")
    (ROOT / "main/rg/rg_images.h").write_text("".join(hdr), encoding="utf-8")
    return total


# ---------------------------------------------------------------- sounds
SOUND_SOURCES = [("droplet", "snd_A_droplet.wav"), ("bell", "snd_B_bell.wav"),
                 ("marimba", "snd_C_marimba.wav")]
SOUND_GAIN = 0.6     # source peaks at 0.8 FS; keep key sounds gentle
SILENCE_GAP_S = 0.02


def regions(x, sr):
    nz = np.where(np.abs(x) > 30)[0]
    regs, start, prev = [], nz[0], nz[0]
    for i in nz[1:]:
        if i - prev > sr * SILENCE_GAP_S:
            regs.append((start, prev + 1))
            start = i
        prev = i
    regs.append((start, prev + 1))
    return regs


def emit_sounds():
    music = ROOT / "assets/music/release_guidance"
    parts = [HEADER, '#include "rg_sound_data.h"\n\n']
    table = []
    total = 0
    for name, fname in SOUND_SOURCES:
        with wave.open(str(music / fname)) as w:
            if w.getframerate() != 24000 or w.getsampwidth() != 2 or w.getnchannels() != 1:
                raise SystemExit(f"{fname}: expected 24 kHz mono PCM16")
            x = np.frombuffer(w.readframes(w.getnframes()), "<i2").astype(np.float64)
        regs = regions(x, 24000)
        # Reference files: three taps, then the two-note confirm phrase.
        if len(regs) < 4:
            raise SystemExit(f"{fname}: unexpected layout {regs}")
        tap = x[regs[0][0]:regs[0][1]]
        confirm = x[regs[3][0]:regs[-1][1]]
        for kind, pcm in (("tap", tap), ("confirm", confirm)):
            pcm = np.clip(np.round(pcm * SOUND_GAIN), -32768, 32767).astype("<i2")
            sym = f"rg_pcm_{name}_{kind}"
            total += pcm.nbytes
            vals = ", ".join(str(v) for v in pcm.tolist())
            parts.append(f"static const int16_t {sym}[{len(pcm)}] = {{{vals}}};\n\n")
            table.append((name, kind, sym, len(pcm)))
    parts.append("const rg_sound_clip_t RG_SOUND_CLIPS[RG_SOUND_BANK_COUNT][RG_SOUND_KIND_COUNT] = {\n")
    for i in range(0, len(table), 2):
        (n, _, tap_sym, tap_len), (_, _, con_sym, con_len) = table[i], table[i + 1]
        parts.append(f"    {{{{{tap_sym}, {tap_len}}}, {{{con_sym}, {con_len}}}}},  // {n}\n")
    parts.append("};\n")
    (ROOT / "main/rg/rg_sound_data.c").write_text("".join(parts), encoding="utf-8")
    return total


def main():
    sprites = all_sprites()
    img_bytes = emit_images(sprites)
    snd_bytes = emit_sounds()
    print(f"images: {img_bytes} bytes, sounds: {snd_bytes} bytes")


if __name__ == "__main__":
    main()
