#!/usr/bin/env python3
"""Generate main/rg/rg_content.{h,c} and font character inventories from rg_spec.

Usage: python3 tools/release_guidance/gen_content.py [--check]
--check exits non-zero when the committed outputs differ from the spec.
Only the Python standard library is required.
"""
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
sys.path.insert(0, str(HERE))
import rg_spec as S  # noqa: E402

OUT_H = ROOT / "main/rg/rg_content.h"
OUT_C = ROOT / "main/rg/rg_content.c"
CHARS_DIR = ROOT / "assets/fonts/release_guidance"

HEADER = "// Generated by tools/release_guidance/gen_content.py from rg_spec.py. Do not edit.\n"


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def font_enum(name):
    return "RG_FONT_" + name.upper()


def line_baselines(kind, base_font, n):
    if kind == "entry":
        return list(S.ENTRY_BASELINES)
    if kind == "willing":
        return list(S.WILLING_BASELINES)
    pitch = S.LINE_PITCH[base_font]
    y0 = S.QUESTION_CENTER_Y - (n - 1) * pitch / 2.0 + S.QUESTION_BASELINE_OFFSET
    return [int(round(y0 + i * pitch)) for i in range(n)]


def validate():
    font_names = [f for f, _ in S.FONTS]
    for sid, kind, base, emph, source, lines in S.SENTENCES:
        joined = "".join(t for line in lines for t, _ in line)
        if joined != source:
            raise SystemExit(f"{sid}: line segments {joined!r} != source {source!r}")
        if base not in font_names or emph not in font_names:
            raise SystemExit(f"{sid}: unknown font")
        for line in lines:
            text = "".join(t for t, _ in line)
            if text in ("吗？", "？", "，", "。"):
                raise SystemExit(f"{sid}: orphan line {text!r}")
        if kind in ("entry", "willing") and len(lines) != 2:
            raise SystemExit(f"{sid}: {kind} layout needs exactly two lines")
    ids = {s[0] for s in S.SENTENCES}
    for name, seq in S.SEQUENCES.items():
        for sid in seq:
            if sid not in ids:
                raise SystemExit(f"sequence {name}: unknown sentence {sid}")


def font_charsets():
    sets = {f: set() for f, _ in S.FONTS}
    for sid, kind, base, emph, source, lines in S.SENTENCES:
        for line in lines:
            for text, is_emph in line:
                sets[emph if is_emph else base].update(text)
    for o in S.ENTRY_OPTIONS + S.WILLING_OPTIONS:
        sets[S.OPTION_FONT].update(o)
    for w in S.STATUS_WORDS:
        sets[S.STATUS_FONT].update(w)
    return {k: "".join(sorted(v)) for k, v in sets.items()}


def render():
    validate()
    h = [HEADER, "#pragma once\n\n#include <stdint.h>\n\n"]
    h.append(f"#define RG_SCREEN_W {S.SCREEN_W}\n#define RG_SCREEN_H {S.SCREEN_H}\n\n")
    h.append("typedef enum {\n")
    for name, px in S.FONTS:
        h.append(f"    {font_enum(name)},  // {px} px\n")
    h.append("    RG_FONT_COUNT\n} rg_font_id_t;\n\n")
    h.append("extern const uint8_t RG_FONT_PX[RG_FONT_COUNT];\n\n")
    h.append("typedef enum {\n    RG_KIND_ENTRY = 0,\n    RG_KIND_QUESTION,\n"
             "    RG_KIND_WILLING,\n    RG_KIND_NOTE,\n} rg_kind_t;\n\n")
    h.append("typedef struct {\n    const char *text;\n    uint8_t font;   // rg_font_id_t\n"
             "    uint8_t emph;   // 1 = accent colour + underline\n} rg_seg_t;\n\n")
    h.append("typedef struct {\n    uint16_t first_seg;\n    uint8_t seg_count;\n"
             "    int16_t baseline;\n} rg_line_t;\n\n")
    h.append("typedef struct {\n    const char *source;   // exact work-order text\n"
             "    uint8_t kind;         // rg_kind_t\n    uint8_t first_line;\n"
             "    uint8_t line_count;\n} rg_sentence_t;\n\n")
    h.append("typedef enum {\n")
    for s in S.SENTENCES:
        h.append(f"    RG_S_{s[0]},\n")
    h.append("    RG_SENTENCE_COUNT\n} rg_sentence_id_t;\n\n")
    h.append("typedef enum {\n")
    for name in S.SEQUENCES:
        h.append(f"    RG_SEQ_{name},\n")
    h.append("    RG_SEQ_COUNT\n} rg_seq_id_t;\n\n")
    h.append("typedef struct {\n    const uint8_t *items;  // rg_sentence_id_t\n"
             "    uint8_t count;\n} rg_seq_t;\n\n")
    h.append("typedef struct {\n    uint32_t top, bottom, text, dim, faint, accent, cloud;\n"
             "} rg_palette_t;\n\n")
    h.append("typedef enum {\n")
    for name in S.THEMES:
        h.append(f"    RG_PALETTE_{name.upper()},\n")
    h.append("    RG_PALETTE_COUNT\n} rg_palette_id_t;\n\n")
    h.append("typedef struct { int16_t x, y; uint8_t size10; uint16_t phase; } rg_star_t;\n")
    h.append("typedef struct { int16_t x, y; uint8_t scale100; } rg_cloud_pos_t;\n\n")
    for decl in [
        "const rg_seg_t RG_SEGS[]", "const rg_line_t RG_LINES[]",
        "const rg_sentence_t RG_SENTENCES[RG_SENTENCE_COUNT]",
        "const rg_seq_t RG_SEQS[RG_SEQ_COUNT]",
        "const char *const RG_ENTRY_OPTIONS[2]", "const char *const RG_WILLING_OPTIONS[2]",
        "const char *const RG_STATUS_WORDS[]",
        "const rg_palette_t RG_PALETTES[RG_PALETTE_COUNT]",
        "const rg_star_t RG_STARS[]", "const rg_cloud_pos_t RG_CLOUDS[]",
    ]:
        h.append(f"extern {decl};\n")
    h.append("\n")
    consts = {
        "RG_STAR_COUNT": len(S.STARS), "RG_CLOUD_COUNT": len(S.CLOUDS),
        "RG_CLOUD_WRAP": S.CLOUD_WRAP,
        "RG_STATUS_MUTED": 0, "RG_STATUS_SOUND": 1, "RG_STATUS_AUTO": 2,
        "RG_STATUS_DUSK": 3, "RG_STATUS_MORNING": 4,
        "RG_OPTION_FONT": font_enum(S.OPTION_FONT), "RG_STATUS_FONT": font_enum(S.STATUS_FONT),
        "RG_ENTRY_OPTION_BASELINE_0": S.ENTRY_OPTION_BASELINES[0],
        "RG_ENTRY_OPTION_BASELINE_1": S.ENTRY_OPTION_BASELINES[1],
        "RG_WILLING_OPTION_BASELINE_0": S.WILLING_OPTION_BASELINES[0],
        "RG_WILLING_OPTION_BASELINE_1": S.WILLING_OPTION_BASELINES[1],
        "RG_OPTION_DOT_GAP": S.OPTION_DOT_GAP, "RG_OPTION_DOT_RADIUS": S.OPTION_DOT_RADIUS,
        "RG_OPTION_DOT_RISE_PCT": S.OPTION_DOT_RISE_PCT,
        "RG_UNDERLINE_DROP": S.UNDERLINE_DROP, "RG_UNDERLINE_SLANT": S.UNDERLINE_SLANT,
        "RG_UNDERLINE_INSET": S.UNDERLINE_INSET, "RG_UNDERLINE_WIDTH": S.UNDERLINE_WIDTH,
        "RG_UNDERLINE_OPA": S.UNDERLINE_OPA, "RG_NOTE_OPA": S.NOTE_OPA,
        "RG_STATUS_BASELINE": S.STATUS_BASELINE,
        "RG_HINT_X": S.HINT_X, "RG_HINT_Y_UP": S.HINT_Y_UP,
        "RG_HINT_Y_DOWN": S.HINT_Y_DOWN, "RG_HINT_Y_OK": S.HINT_Y_OK,
        "RG_MOON_X": S.MOON["x"], "RG_MOON_Y": S.MOON["y"], "RG_MOON_COLOR": f"0x{S.MOON['color']:06X}",
        "RG_SUN_X": S.SUN["x"], "RG_SUN_Y": S.SUN["y"],
        "RG_SUN_COLOR": f"0x{S.SUN['color']:06X}", "RG_SUN_RAY_COLOR": f"0x{S.SUN['ray_color']:06X}",
        "RG_RAINBOW_Y": S.RAINBOW["y"], "RG_RAINBOW_X_RIGHT": S.RAINBOW["x_right"],
        "RG_RAINBOW_X_LEFT": S.RAINBOW["x_left"],
        "RG_FX_PERIOD_MS": S.FX_PERIOD_MS, "RG_RAIN_DROPS_DEFAULT": S.RAIN_DROPS,
        "RG_LEAVES_DEFAULT": S.LEAVES,
    }
    for k, v in consts.items():
        h.append(f"#define {k} {v}\n")

    c = [HEADER, '#include "rg_content.h"\n\n']
    c.append("const uint8_t RG_FONT_PX[RG_FONT_COUNT] = {" +
             ", ".join(str(px) for _, px in S.FONTS) + "};\n\n")
    segs, lines_out, sents = [], [], []
    for sid, kind, base, emph, source, lines in S.SENTENCES:
        first_line = len(lines_out)
        for line, baseline in zip(lines, line_baselines(kind, base, len(lines))):
            first_seg = len(segs)
            for text, is_emph in line:
                segs.append((text, emph if is_emph else base, is_emph))
            lines_out.append((first_seg, len(line), baseline))
        sents.append((sid, source, kind, first_line, len(lines)))
    c.append("const rg_seg_t RG_SEGS[] = {\n")
    for text, font, is_emph in segs:
        c.append(f"    {{{c_str(text)}, {font_enum(font)}, {1 if is_emph else 0}}},\n")
    c.append("};\n\nconst rg_line_t RG_LINES[] = {\n")
    for first, count, baseline in lines_out:
        c.append(f"    {{{first}, {count}, {baseline}}},\n")
    c.append("};\n\nconst rg_sentence_t RG_SENTENCES[RG_SENTENCE_COUNT] = {\n")
    for sid, source, kind, first, count in sents:
        c.append(f"    [RG_S_{sid}] = {{{c_str(source)}, RG_KIND_{kind.upper()}, {first}, {count}}},\n")
    c.append("};\n\n")
    for name, seq in S.SEQUENCES.items():
        c.append(f"static const uint8_t SEQ_{name}[] = {{" +
                 ", ".join(f"RG_S_{x}" for x in seq) + "};\n")
    c.append("\nconst rg_seq_t RG_SEQS[RG_SEQ_COUNT] = {\n")
    for name, seq in S.SEQUENCES.items():
        c.append(f"    [RG_SEQ_{name}] = {{SEQ_{name}, {len(seq)}}},\n")
    c.append("};\n\n")
    c.append("const char *const RG_ENTRY_OPTIONS[2] = {" +
             ", ".join(c_str(x) for x in S.ENTRY_OPTIONS) + "};\n")
    c.append("const char *const RG_WILLING_OPTIONS[2] = {" +
             ", ".join(c_str(x) for x in S.WILLING_OPTIONS) + "};\n")
    c.append("const char *const RG_STATUS_WORDS[] = {" +
             ", ".join(c_str(x) for x in S.STATUS_WORDS) + "};\n\n")
    c.append("const rg_palette_t RG_PALETTES[RG_PALETTE_COUNT] = {\n")
    for name, t in S.THEMES.items():
        vals = ", ".join(f"0x{t[k]:06X}" for k in
                         ("top", "bottom", "text", "dim", "faint", "accent", "cloud"))
        c.append(f"    [RG_PALETTE_{name.upper()}] = {{{vals}}},\n")
    c.append("};\n\nconst rg_star_t RG_STARS[] = {\n")
    for x, y, s10, ph in S.STARS:
        c.append(f"    {{{x}, {y}, {s10}, {ph}}},\n")
    c.append("};\n\nconst rg_cloud_pos_t RG_CLOUDS[] = {\n")
    for x, y, sc in S.CLOUDS:
        c.append(f"    {{{x}, {y}, {int(round(sc * 100))}}},\n")
    c.append("};\n")

    charsets = font_charsets()
    return "".join(h), "".join(c), charsets


def main():
    check = "--check" in sys.argv[1:]
    h, c, charsets = render()
    outputs = {OUT_H: h, OUT_C: c}
    for name, chars in charsets.items():
        outputs[CHARS_DIR / f"rg_wenkai_{name}.chars"] = chars + "\n"
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8")
    if check and stale:
        for p in stale:
            print(f"stale: {p.relative_to(ROOT)}", file=sys.stderr)
        return 1
    if not check:
        for name, chars in charsets.items():
            print(f"{name}: {len(chars)} glyphs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
