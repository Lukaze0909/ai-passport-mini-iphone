def rgb565_bytes(im, alpha):
    im = im.convert("RGBA")
    px = im.tobytes()
    out = bytearray()
    alpha_plane = bytearray()
    # 4x4 ordered dither before truncating to RGB565 (smooth gradients on glass).
    bayer = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
    w = im.width
    for i in range(0, len(px), 4):
        r, g, b, a = px[i], px[i + 1], px[i + 2], px[i + 3]
        x, y = (i // 4) % w, (i // 4) // w
        t = (bayer[y & 3][x & 3] + 0.5) / 16.0
        r5 = min(31, int(r / 255 * 31 + t))
        g6 = min(63, int(g / 255 * 63 + t))
        b5 = min(31, int(b / 255 * 31 + t))
        v = (r5 << 11) | (g6 << 5) | b5
        out += bytes((v & 255, v >> 8))
        alpha_plane.append(a)
    return bytes(out) + (bytes(alpha_plane) if alpha else b"")


def emit(images):
    c = [HEADER, '#include "cs_assets.h"\n\n']
    h = [HEADER, "#pragma once\n\n#include \"lvgl.h\"\n\n"]
    total = 0
    for name, (im, alpha) in images.items():
        payload = rgb565_bytes(im, alpha)
        total += len(payload)
        cf = "LV_COLOR_FORMAT_RGB565A8" if alpha else "LV_COLOR_FORMAT_RGB565"
        rows = [",".join(f"0x{b:02X}" for b in payload[i:i + 24]) for i in range(0, len(payload), 24)]
        c.append(f"static const uint8_t {name}_map[] __attribute__((aligned(4))) = {{\n" + ",\n".join(rows) + "\n};\n")
        c.append(f"const lv_image_dsc_t cs_img_{name} = {{\n    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
                 f"    .header.cf = {cf},\n    .header.w = {im.width},\n    .header.h = {im.height},\n"
                 f"    .header.stride = {im.width * 2},\n    .data_size = sizeof({name}_map),\n"
                 f"    .data = {name}_map,\n}};\n\n")
        h.append(f"extern const lv_image_dsc_t cs_img_{name};  // {im.width}x{im.height} {cf[16:]}\n")
    h.append("\n// Layout shared with cs_ui.c (pixels).\n")
    for k, v in defines.items():
        h.append(f"#define {k} {v}\n")
    h.append(f"static const int16_t CS_HOME_POS[{HOME_COUNT}][2] = {{\n")
    h.append(",\n".join(f"    {{{x}, {y}}}" for x, y in (home_pos(i) for i in range(HOME_COUNT))))
    h.append("\n};\n")
    h.append("extern const lv_image_dsc_t *const CS_IMG_WX_BIG[7];\n")
    h.append("extern const lv_image_dsc_t *const CS_IMG_WX_SMALL[7];\n")
    h.append("extern const lv_image_dsc_t *const CS_IMG_CELL[5];\n")
    c.append("const lv_image_dsc_t *const CS_IMG_WX_BIG[7] = {" +
             ", ".join(f"&cs_img_wx_big_{k}" for k in WX_KINDS) + "};\n")
    c.append("const lv_image_dsc_t *const CS_IMG_WX_SMALL[7] = {" +
             ", ".join(f"&cs_img_wx_small_{k}" for k in WX_KINDS) + "};\n")
    c.append("const lv_image_dsc_t *const CS_IMG_CELL[5] = {" +
             ", ".join(f"&cs_img_cell{i}" for i in range(5)) + "};\n")
    (ROOT / "main/classic/cs_assets.c").write_text("".join(c), encoding="utf-8")
    (ROOT / "main/classic/cs_assets.h").write_text("".join(h), encoding="utf-8")
    return total


