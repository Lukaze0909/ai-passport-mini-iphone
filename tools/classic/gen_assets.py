def ic_astro(t, s):
    """Astro dice: a gold d12 (a pentagon face with its facets) on a night sky,
    a few white stars and a gold sparkle."""
    d = ImageDraw.Draw(t)
    rnd = random.Random(12)
    for _ in range(9):
        x, y, r = rnd.uniform(.08, .92) * s, rnd.uniform(.06, .94) * s, rnd.choice((.012, .018, .024)) * s
        d.ellipse([x - r, y - r, x + r, y + r], fill=(255, 255, 255, rnd.randint(150, 240)))
    cx, cy, R = s * .47, s * .56, s * .31

    def pent(r, rot=-90):
        return [(cx + r * math.cos(math.radians(rot + k * 72)), cy + r * math.sin(math.radians(rot + k * 72)))
                for k in range(5)]
    outer = pent(R)
    inner = pent(R * .52)
    d.polygon(outer, fill=(232, 176, 52, 255))
    for k in range(5):                       # facets: lighter towards the top-left
        a, b = outer[k], outer[(k + 1) % 5]
        ia, ib = inner[k], inner[(k + 1) % 5]
        shade = (255, 214, 96, 255) if k in (3, 4) else (214, 150, 36, 255) if k in (1, 2) else (238, 186, 64, 255)
        d.polygon([a, b, ib, ia], fill=shade)
    d.polygon(inner, fill=(255, 222, 120, 255))
    for k in range(5):
        d.line([outer[k], inner[k]], fill=(160, 104, 20, 255), width=max(1, int(s * .02)))
    d.polygon(inner, outline=(160, 104, 20, 255), width=max(1, int(s * .02)))
    # a four-point sparkle top-right
    sx, sy, sr = s * .80, s * .20, s * .11
    d.polygon([(sx, sy - sr), (sx + sr * .25, sy - sr * .25), (sx + sr, sy), (sx + sr * .25, sy + sr * .25),
               (sx, sy + sr), (sx - sr * .25, sy + sr * .25), (sx - sr, sy), (sx - sr * .25, sy - sr * .25)],
              fill=(255, 226, 120, 255))


def home_apps():
    apps = list(m2.APPS)
    # The calendar icon (weekday + day drawn live) opens the daily Bingo card.
    apps[1] = ("Bingo", apps[1][1], apps[1][2], ic_calendar_blank)
    # The old Photos slot: astro dice (占星骰子).
    apps[2] = ("占星", (206, 196, 242), (124, 108, 190), ic_astro)
    apps[3] = (apps[3][0], apps[3][1], apps[3][2], ic_weather_blank)
    # apps[6] is the Notes app (备忘录, cs_memos) straight from m2.APPS.
    apps.append(("扫雷", (214, 236, 200), (128, 178, 104), ic_mines))
    assert len(apps) == GRID_COUNT
    return apps + list(m2.DOCK)


def bg_home():
    im = m2.droplet_wallpaper()
    status_static(im, (0, 0, 0, 90))
    sz = ICON * S
    # dock shelf first (icons sit on it)
    top, bot = 252 * S, H
    shelf = vgrad(W, bot - top, [(0, (255, 255, 255, 120)), (0.45, (220, 228, 236, 80)),
                                 (0.46, (150, 160, 172, 120)), (1, (120, 130, 140, 150))])
    mask = Image.new("L", (W, bot - top), 0)
    ImageDraw.Draw(mask).polygon([(10 * S, 0), (W - 10 * S, 0), (W, bot - top), (0, bot - top)], fill=255)
    shelf.putalpha(ImageChops.multiply(shelf.split()[3], mask))
    im.alpha_composite(shelf, (0, top))
    ImageDraw.Draw(im).line([(10 * S, top), (W - 10 * S, top)], fill=(255, 255, 255, 220), width=S)
    for i, (n, a, b, f) in enumerate(home_apps()):
        x, y = home_pos(i)
        m2.icon(im, x * S, y * S, sz, a, b, f, n)
        if i >= GRID_COUNT:
            refl = Image.new("RGBA", (W, H), (0, 0, 0, 0))
            tile = vgrad(sz, sz, [(0, b + (255,)), (1, a + (255,))])
            fade = Image.linear_gradient("L").resize((sz, sz)).point(lambda v: int((255 - v) * .25))
            tile.putalpha(ImageChops.multiply(rmask(sz, sz, int(sz * .2)), fade))
            refl.alpha_composite(tile, (x * S, int((y + ICON + 13) * S)))
            im.alpha_composite(refl)
    d = ImageDraw.Draw(im)
    d.ellipse([W / 2 - 2 * S, 238 * S, W / 2 + 2 * S, 242 * S], fill=(255, 255, 255, 230))
    return im


def halo_image():
    n = ICON + 2 * HALO_PAD
    big = Image.new("RGBA", (n * S, n * S), (0, 0, 0, 0))
    p = (HALO_PAD - 4) * S
    ImageDraw.Draw(big).rounded_rectangle([p, p, n * S - p, n * S - p], 12 * S, fill=(255, 255, 255, 255))
    big = big.filter(ImageFilter.GaussianBlur(2.4 * S))
    # Stronger than the mockup's halo: it is the only selection cue on the device.
    big.putalpha(big.split()[3].point(lambda a: min(255, int(a * 1.25))))
    hole = Image.new("L", (n * S, n * S), 255)
    hole.paste(ImageChops.invert(rmask(ICON * S, ICON * S, int(ICON * S * .2))), (HALO_PAD * S, HALO_PAD * S))
    big.putalpha(ImageChops.multiply(big.split()[3], hole))
    return big


