#!/usr/bin/env python3
"""Game art for Mines (对战扫雷) and Bingo: small A8 glyphs drawn on the device
in any colour (cell markers, the Bingo check) and the big hand-lettered words
of the sticky notes (DEAD! / DEAD AGAIN! / YOU WIN! / BINGO! in blue capitals).
Writes main/classic/cs_mines_art.{c,h}. Pillow + Noto Sans CJK Bold (as gen_assets.py).

    python3 tools/classic/gen_mines_art.py [preview_dir]
"""
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
FONT = "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"
K = 4                       # supersampling
HEADER = "// Generated by tools/classic/gen_mines_art.py. Do not edit.\n"
PREVIEW = Path(sys.argv[1]) if len(sys.argv) > 1 else None


def canvas(w, h):
    return Image.new("L", (w * K, h * K), 0)


def done(im, w, h):
    return im.resize((w, h), Image.LANCZOS)


def mine(sz=18):
    im = canvas(sz, sz)
    d = ImageDraw.Draw(im)
    c = sz * K / 2
    r = sz * K * 0.30
    for a in range(8):                                   # spikes
        t = a * math.pi / 4
        x, y = math.cos(t), math.sin(t)
        d.line([(c, c), (c + x * sz * K * 0.47, c + y * sz * K * 0.47)], fill=255, width=int(K * 1.6))
    d.ellipse([c - r, c - r, c + r, c + r], fill=255)
    h = sz * K * 0.08                                    # shine: a hole the tile shows through
    d.ellipse([c - r * 0.55 - h, c - r * 0.55 - h, c - r * 0.55 + h, c - r * 0.55 + h], fill=0)
    return done(im, sz, sz)


def flag(sz=16):
    im = canvas(sz, sz)
    d = ImageDraw.Draw(im)
    s = sz * K
    d.rectangle([s * .30, s * .12, s * .38, s * .80], fill=255)               # pole
    d.polygon([(s * .38, s * .10), (s * .86, s * .30), (s * .38, s * .52)], fill=255)
    d.rounded_rectangle([s * .14, s * .78, s * .62, s * .90], radius=s * .04, fill=255)   # foot
    return done(im, sz, sz)


def foot(sz=18):
    """Two small bare footprints (like the emoji), the left one lower."""
    im = canvas(sz, sz)
    d = ImageDraw.Draw(im)
    s = sz * K

    def one(x, y, mirror):
        d.ellipse([x, y + s * .12, x + s * .24, y + s * .40], fill=255)            # ball of the foot
        d.ellipse([x + s * .04, y + s * .34, x + s * .20, y + s * .52], fill=255)  # arch
        d.ellipse([x + s * .03, y + s * .50, x + s * .21, y + s * .64], fill=255)  # heel
        toes = ((.02, .05, .055), (.10, .01, .05), (.18, .03, .045))
        for dx, dy, r in toes:
            cx = x + s * (dx + .02 if not mirror else .22 - dx)
            cy = y + s * dy + s * .03
            d.ellipse([cx - s * r, cy - s * r, cx + s * r, cy + s * r], fill=255)

    one(s * .10, s * .32, False)
    one(s * .58, s * .02, True)
    return done(im, sz, sz)


def tick(sz=30):
    """A fat hand-drawn check mark (the Bingo cell watermark), round ends."""
    im = canvas(sz, sz)
    d = ImageDraw.Draw(im)
    s = sz * K
    w = int(s * .16)
    pts = [(s * .14, s * .54), (s * .40, s * .78), (s * .86, s * .22)]
    d.line(pts, fill=255, width=w, joint="curve")
    for x, y in (pts[0], pts[2]):
        d.ellipse([x - w / 2, y - w / 2, x + w / 2, y + w / 2], fill=255)
    return done(im, sz, sz)


def word(text, h=58, size=60, shear=0.18, angle=-4):
    """Marker-ish capitals: bold face, italic shear, a small tilt, soft edge."""
    f = ImageFont.truetype(FONT, size * K, index=0)
    x0, y0, x1, y1 = f.getbbox(text)
    w = x1 - x0 + int(size * K * 0.5)
    im = Image.new("L", (w, (y1 - y0) + int(size * K * 0.5)), 0)
    ImageDraw.Draw(im).text((size * K * 0.25 - x0, size * K * 0.25 - y0), text, font=f, fill=255)
    im = im.transform(im.size, Image.AFFINE, (1, shear, -shear * im.height / 2, 0, 1, 0), Image.BICUBIC)
    im = im.rotate(-angle, resample=Image.BICUBIC, expand=True)
    im = im.filter(ImageFilter.GaussianBlur(K * 0.4))
    im = im.crop(im.getbbox())
    ww = max(1, round(im.width * h / im.height))
    if ww > 184:                                         # fits the 196 px sticky note
        h, ww = round(h * 184 / ww), 184
    return im.resize((ww, h), Image.LANCZOS)


def emit(images):
    c = [HEADER, '#include "cs_mines_art.h"\n\n']
    hh = [HEADER, "#pragma once\n\n#include \"lvgl.h\"\n\n"]
    for name, im in images.items():
        data = im.tobytes()
        rows = [",".join(f"0x{b:02X}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
        c.append(f"static const uint8_t {name}_map[] = {{\n" + ",\n".join(rows) + "\n};\n")
        c.append(f"const lv_image_dsc_t cs_mines_{name} = {{\n    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
                 f"    .header.cf = LV_COLOR_FORMAT_A8,\n    .header.w = {im.width},\n"
                 f"    .header.h = {im.height},\n    .header.stride = {im.width},\n"
                 f"    .data_size = sizeof({name}_map),\n    .data = {name}_map,\n}};\n\n")
        hh.append(f"extern const lv_image_dsc_t cs_mines_{name};  // {im.width}x{im.height} A8\n")
    (ROOT / "main/classic/cs_mines_art.c").write_text("".join(c), encoding="utf-8")
    (ROOT / "main/classic/cs_mines_art.h").write_text("".join(hh), encoding="utf-8")


def main():
    images = {
        "mine": mine(), "flag": flag(), "foot": foot(),
        "dead": word("DEAD!"), "again": word("AGAIN!"),
        "you": word("YOU"), "win": word("WIN!"),
        "tick": tick(), "bingo": word("BINGO!"),
    }
    emit(images)
    if PREVIEW:
        PREVIEW.mkdir(parents=True, exist_ok=True)
        for name, im in images.items():
            big = im.resize((im.width * 4, im.height * 4), Image.NEAREST) if im.width < 40 else im
            Image.merge("RGB", [Image.eval(big, lambda v: 255 - v)] * 3).save(PREVIEW / f"mines_{name}.png")
    print("bytes:", sum(len(im.tobytes()) for im in images.values()))


if __name__ == "__main__":
    main()
