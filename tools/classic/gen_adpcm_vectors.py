#!/usr/bin/env python3
"""Reference IMA ADPCM encoder (written from the IMA/DVI spec, independent of
main/classic/cs_logic.c) and the host-test vector tests/cs_adpcm_vectors.h.

Usage: python3 tools/classic/gen_adpcm_vectors.py
Input is deterministic (sine + LCG noise + a step and clipping run) so the
vector can be regenerated byte for byte.
"""
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
STEPS = [7, 8, 9, 10, 11, 12, 13, 14, 16, 17, 19, 21, 23, 25, 28, 31, 34, 37, 41, 45, 50, 55, 60,
         66, 73, 80, 88, 97, 107, 118, 130, 143, 157, 173, 190, 209, 230, 253, 279, 307, 337, 371,
         408, 449, 494, 544, 598, 658, 724, 796, 876, 963, 1060, 1166, 1282, 1411, 1552, 1707,
         1878, 2066, 2272, 2499, 2749, 3024, 3327, 3660, 4026, 4428, 4871, 5358, 5894, 6484, 7132,
         7845, 8630, 9493, 10442, 11487, 12635, 13899, 15289, 16818, 18500, 20350, 22385, 24623,
         27086, 29794, 32767]
INDEX_ADJ = [-1, -1, -1, -1, 2, 4, 6, 8]


def encode(samples, pred=0, index=0):
    codes = []
    for s in samples:
        step = STEPS[index]
        diff = s - pred
        sign = 8 if diff < 0 else 0
        diff = abs(diff)
        code = 0
        vpdiff = step >> 3
        if diff >= step:
            code |= 4
            diff -= step
            vpdiff += step
        step2 = step >> 1
        if diff >= step2:
            code |= 2
            diff -= step2
            vpdiff += step2
        step3 = step >> 2
        if diff >= step3:
            code |= 1
            vpdiff += step3
        pred = pred - vpdiff if sign else pred + vpdiff
        pred = max(-32768, min(32767, pred))
        index = max(0, min(88, index + INDEX_ADJ[code]))
        codes.append(code | sign)
    out = bytes((codes[i] | (codes[i + 1] << 4)) for i in range(0, len(codes) - 1, 2))
    return out, pred, index


def make_input(n=512):
    x, seed = [], 12345
    for i in range(n):
        seed = (seed * 1103515245 + 12345) & 0x7FFFFFFF
        noise = (seed >> 16) % 1001 - 500
        v = int(12000 * math.sin(2 * math.pi * 440 * i / 16000)) + noise
        if 300 <= i < 340:
            v = 32767                      # clipping run
        if 400 <= i < 420:
            v = -30000                     # big negative step
        x.append(max(-32768, min(32767, v)))
    return x


def c_array(name, ctype, values, per=12):
    rows = [", ".join(str(v) for v in values[i:i + per]) for i in range(0, len(values), per)]
    return f"static const {ctype} {name}[{len(values)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"


def main():
    x = make_input()
    full, pred, idx = encode(x)
    half = len(x) // 2
    _, mid_pred, mid_idx = encode(x[:half])
    parts = ["// Generated by tools/classic/gen_adpcm_vectors.py. Do not edit.\n#pragma once\n#include <stdint.h>\n\n",
             c_array("CS_ADPCM_IN", "int16_t", x),
             c_array("CS_ADPCM_OUT", "uint8_t", list(full), 16),
             f"#define CS_ADPCM_MID_PRED {mid_pred}\n#define CS_ADPCM_MID_INDEX {mid_idx}\n",
             f"#define CS_ADPCM_END_PRED {pred}\n#define CS_ADPCM_END_INDEX {idx}\n"]
    (ROOT / "tests/cs_adpcm_vectors.h").write_text("".join(parts), encoding="utf-8")
    print(f"{len(x)} samples -> {len(full)} bytes; mid state {mid_pred}/{mid_idx}; end {pred}/{idx}")


if __name__ == "__main__":
    main()
