#!/usr/bin/env python3
"""Art for the astro dice (占星骰子), round 11b "water" design.

- cs_astro_bg: a procedural lavender water surface (tools/classic/art/astro_water.png,
  generated by art/gen_water.py, no photo needed;
  centre crop to 3:4, 240x320) with the frosted title bar and the frosted Roll
  pill baked in (blur + white, no runtime blur). RGB565, drawn from flash.
- cs_astro_hist: the frosted History panel (220x248 at 10,64), cut from the same
  water so it sits on the background seamlessly. RGB565.
- Result symbols, white on the device: planets and signs from DejaVu Sans
  (44 px), house numbers 1..12 from Noto Sans CJK SC Bold (50 px), a sparkle for
  the empty die. Each is a tight A8 mask plus an A8 glow mask (the mask blurred,
  6 px margin) drawn under it in lavender. Small planets / signs (DejaVu 15 px)
  for the History rows. The wizard hat (ink + gold, RGB565A8) and the clock (A8).
Writes main/classic/cs_astro_art.{c,h}. Pillow only. DejaVu: Bitstream Vera /
DejaVu licence (free to use and modify); Noto: SIL OFL 1.1.

    python3 tools/classic/gen_astro_art.py [preview_dir]
"""
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageFont

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
WATER = HERE / "art" / "astro_water.png"   # regenerate: python3 art/gen_water.py art/astro_water.png 962 586 7
SYM = "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf"
NOTO = "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc"
K = 4                       # supersampling for drawn shapes
HEADER = "// Generated by tools/classic/gen_astro_art.py. Do not edit.\n"
PREVIEW = Path(sys.argv[1]) if len(sys.argv) > 1 else None

W, H = 240, 320
BAR = (0, 14, 240, 54)           # frosted title bar
PILL = (72, 262, 168, 292, 15)   # frosted Roll pill (x0, y0, x1, y1, radius)
PANEL = (10, 64, 230, 312, 14)   # frosted History panel
INK = (88, 78, 140)
GOLD = (236, 190, 72)
GLOW_M = 6                       # glow margin around a mask
GLOW_BLUR = 3.0
GLOW_A = 200 / 255

# Order = CS_ASTRO_PLANETS / CS_ASTRO_SIGNS in cs_logic.c.
PLANETS = "☉☽☿♀♂♃♄♅♆♇☊☋"   # Sun .. South Node
SIGNS = "".join(chr(c) for c in range(0x2648, 0x2654))                                   # Aries .. Pisces


def font(path, px, index=0):
    return ImageFont.truetype(path, px, index=index) if path.endswith(".ttc") else ImageFont.truetype(path, px)


def text_mask(s, path, px, index=0):
    """Tight A8 mask of s at px (rendered at 4x, then reduced)."""
    f = font(path, px * K, index)
    im = Image.new("L", (px * K * 3, px * K * 2), 0)
    ImageDraw.Draw(im).text((px * K // 2, px * K // 3), s, font=f, fill=255)
    box = im.getbbox()
    assert box, f"no ink for {s!r}"
    # pad the crop to a multiple of K so the reduction keeps the ink centred
    x0, y0, x1, y1 = box
    w = -(-(x1 - x0) // K) * K
    h = -(-(y1 - y0) // K) * K
    x0 -= (w - (x1 - x0)) // 2
    y0 -= (h - (y1 - y0)) // 2
    return im.crop((x0, y0, x0 + w, y0 + h)).resize((w // K, h // K), Image.LANCZOS)


def glow_of(m):
    g = Image.new("L", (m.width + 2 * GLOW_M, m.height + 2 * GLOW_M), 0)
    g.paste(m, (GLOW_M, GLOW_M))
    g = g.filter(ImageFilter.GaussianBlur(GLOW_BLUR))
    return g.point(lambda v: int(v * GLOW_A))


def sparkle_mask(side=30):
    s = side * K
    im = Image.new("L", (s, s), 0)
    d = ImageDraw.Draw(im)
    c, r, w = s / 2, s * 0.48, s * 0.07
    d.polygon([(c, c - r), (c + w, c - w), (c + r, c), (c + w, c + w), (c, c + r), (c - w, c + w), (c - r, c),
               (c - w, c - w)], fill=255)
    return im.resize((side, side), Image.LANCZOS)


def water():
    src = Image.open(WATER).convert("RGB")
    sw, sh = src.size
    cw = int(sh * 3 / 4)
    x0 = (sw - cw) // 2
    return src.crop((x0, 0, x0 + cw, sh)).resize((W, H), Image.LANCZOS)


def glass(im, box, r):
    """Frosted glass: the region blurred, 45 % white, rounded, 1 px white rim (as the mockup)."""
    S = K
    big = im.resize((W * S, H * S), Image.LANCZOS)
    x0, y0, x1, y1 = [v * S for v in box]
    reg = big.crop((x0, y0, x1, y1)).filter(ImageFilter.GaussianBlur(6 * S))
    reg = Image.blend(reg, Image.new("RGB", reg.size, (255, 255, 255)), 0.45)
    m = Image.new("L", reg.size, 0)
    ImageDraw.Draw(m).rounded_rectangle([0, 0, reg.width - 1, reg.height - 1], r * S, fill=255)
    big.paste(reg, (x0, y0), m)
    ImageDraw.Draw(big).rounded_rectangle([x0, y0, x1, y1], r * S, outline=(255, 255, 255), width=S)
    return big.resize((W, H), Image.LANCZOS)


def hat_image():
    """Flat wizard hat in the ink colour with a gold band and a small gold star (24 x 22)."""
    w, h = 24, 22
    im = Image.new("RGBA", (w * K, h * K), (0, 0, 0, 0))
    d = ImageDraw.Draw(im)
    cx, cy, r = 12 * K, 12 * K, 9 * K
    ink = INK + (255,)
    d.polygon([(cx - r, cy + r * 0.55), (cx + r, cy + r * 0.55), (cx + r * 0.15, cy - r)], fill=ink)
    d.ellipse([cx - r * 1.15, cy + r * 0.35, cx + r * 1.15, cy + r * 0.8], fill=ink)
    d.rectangle([cx - r * 0.75, cy + r * 0.25, cx + r * 0.75, cy + r * 0.45], fill=GOLD + (255,))
    sx, sy, sr = cx - r * 0.02, cy - r * 0.05, r * 0.32
    pts = []
    for i in range(10):
        a = -math.pi / 2 + i * math.pi / 5
        rr = sr if i % 2 == 0 else sr * 0.45
        pts.append((sx + rr * math.cos(a), sy + rr * math.sin(a)))
    d.polygon(pts, fill=(255, 220, 90, 255))
    return im.convert("RGBa").resize((w, h), Image.LANCZOS).convert("RGBA")


def clock_mask(side=20):
    s = side * K
    im = Image.new("L", (s, s), 0)
    d = ImageDraw.Draw(im)
    c, r, lw = s / 2, 8 * K, 2 * K
    d.ellipse([c - r, c - r, c + r, c + r], outline=255, width=lw)
    d.line([c, c, c, c - r * 0.6], fill=255, width=lw)
    d.line([c, c, c + r * 0.45, c], fill=255, width=lw)
    return im.resize((side, side), Image.LANCZOS)


def rgb565(im):
    out = bytearray()
    px = im.convert("RGB").tobytes()
    for i in range(0, len(px), 3):
        r, g, b = px[i], px[i + 1], px[i + 2]
        v = ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)
        out += bytes((v & 255, v >> 8))
    return bytes(out)


def rgb565_dither(im):
    """4x4 ordered dither before truncating (smooth water, as gen_assets.py)."""
    bayer = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]
    out = bytearray()
    w = im.width
    px = im.convert("RGB").tobytes()
    for i in range(len(px) // 3):
        r, g, b = px[3 * i], px[3 * i + 1], px[3 * i + 2]
        t = (bayer[(i // w) & 3][(i % w) & 3] + 0.5) / 16.0
        v = (min(31, int(r / 255 * 31 + t)) << 11) | (min(63, int(g / 255 * 63 + t)) << 5) | min(31, int(b / 255 * 31 + t))
        out += bytes((v & 255, v >> 8))
    return bytes(out)


def emit(images, tables):
    c = [HEADER, '#include "cs_astro_art.h"\n\n']
    h = [HEADER, "#pragma once\n\n#include \"lvgl.h\"\n\n"]
    total = 0
    for name, (im, cf) in images.items():
        if cf == "A8":
            data, stride = im.tobytes(), im.width
        elif cf == "RGB565":
            data, stride = rgb565_dither(im), im.width * 2
        else:   # RGB565A8
            data, stride = rgb565(im) + im.getchannel("A").tobytes(), im.width * 2
        total += len(data)
        rows = [",".join(f"0x{b:02X}" for b in data[i:i + 24]) for i in range(0, len(data), 24)]
        c.append(f"static const uint8_t {name}_map[] __attribute__((aligned(4))) = {{\n" + ",\n".join(rows) + "\n};\n")
        c.append(f"const lv_image_dsc_t {name} = {{\n    .header.magic = LV_IMAGE_HEADER_MAGIC,\n"
                 f"    .header.cf = LV_COLOR_FORMAT_{cf},\n    .header.w = {im.width},\n"
                 f"    .header.h = {im.height},\n    .header.stride = {stride},\n"
                 f"    .data_size = sizeof({name}_map),\n    .data = {name}_map,\n}};\n\n")
        h.append(f"extern const lv_image_dsc_t {name};  // {im.width}x{im.height} {cf}\n")
    h.append("\n// Layout baked into the background (pixels).\n")
    h.append(f"#define CS_ASTRO_BAR_Y0 {BAR[1]}\n#define CS_ASTRO_BAR_Y1 {BAR[3]}\n")
    h.append(f"#define CS_ASTRO_PILL_X0 {PILL[0]}\n#define CS_ASTRO_PILL_Y0 {PILL[1]}\n"
             f"#define CS_ASTRO_PILL_X1 {PILL[2]}\n#define CS_ASTRO_PILL_Y1 {PILL[3]}\n#define CS_ASTRO_PILL_R {PILL[4]}\n")
    h.append(f"#define CS_ASTRO_PANEL_X0 {PANEL[0]}\n#define CS_ASTRO_PANEL_Y0 {PANEL[1]}\n"
             f"#define CS_ASTRO_PANEL_X1 {PANEL[2]}\n#define CS_ASTRO_PANEL_Y1 {PANEL[3]}\n")
    h.append(f"#define CS_ASTRO_GLOW_M {GLOW_M}\n\n")
    for table, names in tables.items():
        h.append(f"extern const lv_image_dsc_t *const {table}[{len(names)}];\n")
        c.append(f"const lv_image_dsc_t *const {table}[{len(names)}] = {{" + ", ".join(f"&{n}" for n in names)
                 + "};\n")
    (ROOT / "main/classic/cs_astro_art.c").write_text("".join(c), encoding="utf-8")
    (ROOT / "main/classic/cs_astro_art.h").write_text("".join(h), encoding="utf-8")
    return total


def main():
    images, tables = {}, {}
    bg = glass(glass(water(), BAR[:4], 0), PILL[:4], PILL[4])
    images["cs_astro_bg"] = (bg, "RGB565")
    hist = glass(glass(water(), BAR[:4], 0), PANEL[:4], PANEL[4]).crop(PANEL[:4])
    images["cs_astro_hist"] = (hist, "RGB565")
    sets = (("planet", [(c, SYM, 44, 0) for c in PLANETS]),
            ("sign", [(c, SYM, 44, 0) for c in SIGNS]),
            ("house", [(str(n), NOTO, 50, 2) for n in range(1, 13)]))
    for kind, items in sets:
        names, glows = [], []
        for i, (s, path, px, idx) in enumerate(items):
            m = text_mask(s, path, px, idx)
            images[f"cs_astro_{kind}{i}"] = (m, "A8")
            images[f"cs_astro_{kind}{i}_g"] = (glow_of(m), "A8")
            names.append(f"cs_astro_{kind}{i}")
            glows.append(f"cs_astro_{kind}{i}_g")
        tables[f"CS_ASTRO_IMG_{kind.upper()}"] = names
        tables[f"CS_ASTRO_IMG_{kind.upper()}_G"] = glows
    for kind, chars in (("planet", PLANETS), ("sign", SIGNS)):
        names = []
        for i, ch in enumerate(chars):
            images[f"cs_astro_{kind}_s{i}"] = (text_mask(ch, SYM, 15), "A8")
            names.append(f"cs_astro_{kind}_s{i}")
        tables[f"CS_ASTRO_IMG_{kind.upper()}_S"] = names
    sp = sparkle_mask()
    images["cs_astro_sparkle"] = (sp, "A8")
    images["cs_astro_sparkle_g"] = (glow_of(sp), "A8")
    images["cs_astro_hat"] = (hat_image(), "RGB565A8")
    images["cs_astro_clock"] = (clock_mask(), "A8")
    total = emit(images, tables)
    if PREVIEW:
        PREVIEW.mkdir(parents=True, exist_ok=True)
        bg.save(PREVIEW / "astro_bg.png")
        sheet = Image.new("RGB", (12 * 60 + 10, 4 * 64 + 10), (150, 140, 200))
        for row, kind in enumerate(("planet", "sign", "house")):
            for i in range(12):
                g = images[f"cs_astro_{kind}{i}_g"][0]
                m = images[f"cs_astro_{kind}{i}"][0]
                x, y = 5 + i * 60, 5 + row * 64
                sheet.paste(Image.new("RGB", g.size, (120, 100, 200)), (x, y), g)
                sheet.paste(Image.new("RGB", m.size, (255, 255, 255)), (x + GLOW_M, y + GLOW_M), m)
        for i in range(12):
            for k, kind in enumerate(("planet", "sign")):
                m = images[f"cs_astro_{kind}_s{i}"][0]
                sheet.paste(Image.new("RGB", m.size, INK), (5 + i * 60 + k * 20, 5 + 3 * 64), m)
        sheet.save(PREVIEW / "astro_art.png")
    print(f"{len(images)} images, {total} bytes")


if __name__ == "__main__":
    main()
